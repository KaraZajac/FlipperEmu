"""Infrared signals for FlipperEmu's virtual IR receiver (/machine/ir).

The encoders follow the Flipper firmware's own (lib/infrared/encoder_decoder):
the same timings and data layouts, generated by a port of its common encoder
(pulse distance/width and Manchester). The firmware's decoders therefore see
exactly what a real remote produces.

    fe_ir.py NEC 0x04 0x08              -> mark/space durations in µs
    fe_ir.py remote.ir Power            -> a signal from a Flipper .ir file
"""
import pathlib
import sys

# name: (preamble (mark, space) | None, bit1 (mark, space), bit0 (mark, space),
#        manchester, bits, repeats, frame period µs)
SPECS = {
    "NEC":       ((9000, 4500), (560, 1690), (560, 560), False, 32, 1, 110000),
    "NECext":    ((9000, 4500), (560, 1690), (560, 560), False, 32, 1, 110000),
    "NEC42":     ((9000, 4500), (560, 1690), (560, 560), False, 42, 1, 110000),
    "NEC42ext":  ((9000, 4500), (560, 1690), (560, 560), False, 42, 1, 110000),
    "Samsung32": ((4500, 4500), (550, 1650), (550, 550), False, 32, 1, 110000),
    "SIRC":      ((2400, 600), (1200, 600), (600, 600), False, 12, 3, 45000),
    "SIRC15":    ((2400, 600), (1200, 600), (600, 600), False, 15, 3, 45000),
    "SIRC20":    ((2400, 600), (1200, 600), (600, 600), False, 20, 3, 45000),
    "RC5":       (None, (888, 888), (888, 888), True, 14, 1, 114000),
    "RC5X":      (None, (888, 888), (888, 888), True, 14, 1, 114000),
    "RC6":       ((2666, 889), (444, 444), (444, 444), True, 21, 1, 107000),
    "RCA":       ((4000, 4000), (500, 2000), (500, 1000), False, 24, 1, 64000),
    "Pioneer":   ((8500, 4225), (500, 1500), (500, 500), False, 33, 2, 110000),
    "Kaseikyo":  ((3456, 1728), (432, 1296), (432, 432), False, 48, 1, 130000),
}


def _rev8(v):
    return int(f"{v & 0xFF:08b}"[::-1], 2)


def layout(proto, address, command, toggle=0):
    """The data word the firmware's encoder builds (LSB is sent first)."""
    a, c = address, command
    if proto == "NEC":
        return (a & 0xFF) | (~a & 0xFF) << 8 | (c & 0xFF) << 16 | (~c & 0xFF) << 24
    if proto == "NECext":
        return (a & 0xFFFF) | (c & 0xFFFF) << 16
    if proto == "NEC42":
        return (a & 0x1FFF) | (~a & 0x1FFF) << 13 | (c & 0xFF) << 26 | (~c & 0xFF) << 34
    if proto == "NEC42ext":
        return (a & 0x3FFFFFF) | (c & 0xFFFF) << 26
    if proto == "Samsung32":
        return (a & 0xFF) | (a & 0xFF) << 8 | (c & 0xFF) << 16 | (~c & 0xFF) << 24
    if proto.startswith("SIRC"):
        amask = {"SIRC": 0x1F, "SIRC15": 0xFF, "SIRC20": 0x1FFF}[proto]
        return (c & 0x7F) | (a & amask) << 7
    if proto in ("RC5", "RC5X"):
        d = 0x01 | (0x02 if proto == "RC5" else 0) | (0x04 if toggle else 0)
        d |= (_rev8(a) >> 3) << 3
        d |= (_rev8(c) >> 2) << 8
        return ~d & 0xFFFF                      # the encoder inverts its data bytes
    if proto == "RC6":
        return 0x01 | (0x10 if toggle else 0) | _rev8(a) << 5 | _rev8(c) << 13
    if proto == "RCA":
        return (a & 0xF) | (c & 0xFF) << 4 | (~a & 0xF) << 12 | (~c & 0xFF) << 16
    if proto == "Pioneer":
        b = [a & 0xFF, ~a & 0xFF, c & 0xFF, ~c & 0xFF, 0]
        return int.from_bytes(bytes(b), "little")
    if proto == "Kaseikyo":
        ident, vendor = (a >> 24) & 3, (a >> 8) & 0xFFFF
        g1, g2 = (a >> 4) & 0xF, a & 0xF
        b = [vendor & 0xFF, vendor >> 8, 0, 0, 0, 0]
        par = b[0] ^ b[1]
        par = (par & 0xF) ^ (par >> 4)
        b[2] = (par & 0xF) | (g1 << 4)
        b[3] = (g2 & 0xF) | ((c & 0xF) << 4)
        b[4] = ((ident << 6) | (c >> 4)) & 0xFF
        b[5] = b[2] ^ b[3] ^ b[4]
        return int.from_bytes(bytes(b), "little")
    raise ValueError(f"unknown protocol {proto!r}; have {', '.join(SPECS)}")


def frame(proto, address, command, toggle=0):
    """One frame as (level, µs) pairs, ported from infrared_common_encode()."""
    pre, bit1, bit0, manchester, nbits, _, _ = SPECS[proto]
    data = layout(proto, address, command, toggle)
    out, te, done = [], 1, 0                    # te: timings encoded (silence = 0)
    if pre:
        out += [(1, pre[0]), (0, pre[1])]
        te = 3
    while True:
        logic = (data >> done) & 1
        if manchester:                          # infrared_common_encode_manchester
            even = te % 2 == 0
            level = int(even) ^ logic
            dur = bit1[0]
            if proto == "RC6" and done == 4:    # RC6 toggle bit: double width
                dur *= 2
            if even:
                done += 1
            elif level and done + 1 == nbits:
                done += 1                       # no final space
        else:                                   # infrared_common_encode_pdwm
            pwm = bit1[1] == bit0[1]
            if te % 2:
                level, dur = 1, (bit1[0] if logic else bit0[0])
                done += pwm
            else:
                level, dur = 0, (bit1[1] if logic else bit0[1])
                done += not pwm
        te += 1
        out.append((level, dur))
        if done == nbits and level:
            return out


def to_marks_spaces(pairs):
    """Merge equal levels, drop leading silence: [mark, space, mark, ...]."""
    durs, last = [], None
    for level, d in pairs:
        if not durs and not level:
            continue
        if level == last:
            durs[-1] += d
        else:
            durs.append(d)
            last = level
    return durs


def encode(proto, address, command, repeats=None):
    spec = SPECS[proto]
    repeats = spec[5] if repeats is None else repeats
    pairs = []
    for i in range(repeats):
        f = frame(proto, address, command)
        if pairs:
            pairs.append((0, max(spec[6] - sum(d for _, d in f), 5000)))
        pairs += f
    return to_marks_spaces(pairs)


def parse_ir_file(path, name=None):
    """A signal from a Flipper .ir file: ('raw', durations) or ('parsed', p, a, c)."""
    blocks, cur = [], {}
    for line in pathlib.Path(path).read_text().splitlines():
        line = line.strip()
        if line.startswith("#") or not line:
            if cur:
                blocks.append(cur)
                cur = {}
            continue
        key, _, value = line.partition(":")
        cur[key.strip()] = value.strip()
    if cur:
        blocks.append(cur)
    sigs = [b for b in blocks if "name" in b and "type" in b]
    if not sigs:
        raise ValueError(f"{path}: no signals")
    if name:
        sigs = [b for b in sigs if b["name"] == name]
        if not sigs:
            raise ValueError(f"{path}: no signal named {name!r}")
    b = sigs[0]
    if b["type"] == "raw":
        return b["name"], [abs(int(x)) for x in b["data"].split()]
    le = lambda s: int.from_bytes(bytes(int(x, 16) for x in s.split()), "little")
    return b["name"], encode(b["protocol"], le(b["address"]), le(b["command"]))


def main():
    if len(sys.argv) >= 2 and sys.argv[1].endswith(".ir"):
        name, durs = parse_ir_file(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
    elif len(sys.argv) == 4:
        durs = encode(sys.argv[1], int(sys.argv[2], 0), int(sys.argv[3], 0))
    else:
        print(__doc__)
        return 2
    print(" ".join(map(str, durs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
