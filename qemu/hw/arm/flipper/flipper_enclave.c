/*
 * Flipper Zero: the secure enclave as it leaves the factory
 *
 * What the firmware calls the secure enclave is the STM32WB55's own: the
 * FUS's key store on CPU2 (stm32wb55_fus.c) and AES1 (stm32wb55_aes.c). The
 * firmware names a key by its index, the FUS loads it into AES1, and the
 * firmware encrypts with a key it cannot read. Flipper Devices fills the
 * store at the factory (targets/furi_hal_include/furi_hal_crypto.h):
 *
 *   0        the master key: for delivering encrypted keys, never loadable
 *   1..10    the factory keys, 256 bits, the same on every Flipper. Key 1
 *            encrypts the Sub-GHz keystores, key 2 the stock U2F
 *            certificate's private key
 *   11       the device's own key. Left empty: the firmware stores 32
 *            random bytes there the first time one is needed (U2F)
 *   12..100  the user's
 *
 * This file does the factory's part for an emulated Flipper: the board
 * hands it to the FUS as its provisioning (flipper_enclave_setup()), and the
 * FUS runs it when it finds no key file to load.
 *
 * The keys. Flipper Devices' factory keys never leave a Flipper, and they
 * are not here. An emulated Flipper gets eleven keys of its own, the same in
 * every FlipperEmu and public by construction:
 *
 *   key N = SHA-256("FlipperEmu enclave key N")          N = 0 .. 10
 *
 * So what an emulated Flipper encrypts, anybody can decrypt (scripts/
 * fe_enclave.py does), and what a real Flipper encrypted with a factory
 * key - the firmware's stock Sub-GHz keystore, the stock U2F certificate
 * key - an emulated one reads as noise, as before.
 *
 * The self-test. The firmware checks its enclave by encrypting one block
 * with each factory key and comparing with the ciphertext it expects
 * (furi_hal_crypto_enclave_verify(): the desktop does it at every start and
 * shows "Secure Enclave is damaged" otherwise, and
 * furi_hal_crypto_enclave_ensure_key() refuses to make key 11 without it).
 * Only the real keys compute those ten blocks, so for them, and for nothing
 * else, the emulated enclave answers with what the firmware expects: the
 * table below, looked up by key index, IV and input, and only while that
 * index holds the FlipperEmu key above. Every other block, with every key,
 * is plain AES. The ten answers say nothing about the real keys that the
 * firmware's source doesn't already.
 *
 * To see what the firmware does with keys of your own, or with none, edit
 * the key file (./flipperemu enclave): keys that aren't FlipperEmu's own
 * get no answers, and fail the self-test like any wrong key would.
 *
 * Copyright (c) 2026, Kara Zajac
 * SPDX-License-Identifier: BSD-3-Clause
 */
